SET NOCOUNT ON;
PRINT '--- 1. SongSql (home/search) ---';
SELECT s.ID_SONG, s.SONG_NAME, ISNULL(s.PLAYS,0) AS PLAYS,
 (SELECT TOP 1 a.ID_ALBUM FROM TBL_TRACKLIST t INNER JOIN TBL_ALBUM a ON a.ID_ALBUM=t.ID_ALBUM WHERE t.ID_SONG=s.ID_SONG) AS ALBUM_ID,
 (SELECT TOP 1 a.TITLE_ALBUM FROM TBL_TRACKLIST t INNER JOIN TBL_ALBUM a ON a.ID_ALBUM=t.ID_ALBUM WHERE t.ID_SONG=s.ID_SONG) AS ALBUM_NAME,
 (SELECT TOP 1 a.ALBUM_IMAGE_PATH FROM TBL_TRACKLIST t INNER JOIN TBL_ALBUM a ON a.ID_ALBUM=t.ID_ALBUM WHERE t.ID_SONG=s.ID_SONG) AS COVER,
 (SELECT TOP 1 ar.ID_ARTIST FROM TBL_PLAYER p INNER JOIN TBL_ARTIST ar ON ar.ID_ARTIST=p.ID_ARTIST WHERE p.ID_SONG=s.ID_SONG) AS ARTIST_ID,
 (SELECT TOP 1 LTRIM(RTRIM(ar.ARTIST_NAME + ISNULL(' ' + ar.ARTIST_LASTNAME,''))) FROM TBL_PLAYER p INNER JOIN TBL_ARTIST ar ON ar.ID_ARTIST=p.ID_ARTIST WHERE p.ID_SONG=s.ID_SONG) AS ARTIST
FROM TBL_SONG s ORDER BY ISNULL(s.PLAYS,0) DESC, s.SONG_NAME;

PRINT '--- 2. Login ---';
SELECT TOP 1 ID_USER, USERNAME, USER_TYPE FROM TBL_USER
WHERE USERNAME='userAdmin'
AND (UPPER(PASSWORD)=UPPER(CONVERT(varchar(40),HASHBYTES('SHA1',CONVERT(varchar(50),'12345678')),2)) OR PASSWORD='12345678');

PRINT '--- 3. Admin songs aggregation ---';
SELECT s.SONG_NAME,
 STUFF((SELECT ', ' + ar.ARTIST_NAME + ISNULL(' ' + ar.ARTIST_LASTNAME,'') FROM TBL_PLAYER p INNER JOIN TBL_ARTIST ar ON ar.ID_ARTIST=p.ID_ARTIST WHERE p.ID_SONG=s.ID_SONG FOR XML PATH('')),1,2,'') AS ARTISTS,
 STUFF((SELECT ', ' + a.TITLE_ALBUM FROM TBL_TRACKLIST t INNER JOIN TBL_ALBUM a ON a.ID_ALBUM=t.ID_ALBUM WHERE t.ID_SONG=s.ID_SONG FOR XML PATH('')),1,2,'') AS ALBUMS
FROM TBL_SONG s ORDER BY s.SONG_NAME;

PRINT '--- 4. Featured album ---';
SELECT TOP 1 a.ID_ALBUM, a.TITLE_ALBUM, a.RELEASE_YEAR, a.ALBUM_IMAGE_PATH,
 (SELECT COUNT(*) FROM TBL_TRACKLIST t WHERE t.ID_ALBUM=a.ID_ALBUM) AS TRACKS,
 (SELECT TOP 1 LTRIM(RTRIM(ar.ARTIST_NAME + ISNULL(' ' + ar.ARTIST_LASTNAME,'')))
   FROM TBL_TRACKLIST t INNER JOIN TBL_PLAYER p ON p.ID_SONG=t.ID_SONG
   INNER JOIN TBL_ARTIST ar ON ar.ID_ARTIST=p.ID_ARTIST WHERE t.ID_ALBUM=a.ID_ALBUM) AS ARTIST
FROM TBL_ALBUM a ORDER BY (SELECT COUNT(*) FROM TBL_TRACKLIST t WHERE t.ID_ALBUM=a.ID_ALBUM) DESC, a.RELEASE_YEAR DESC;

PRINT '--- 5. Playlist tracks (id=1) ---';
SELECT s.SONG_NAME FROM TBL_SONG s
INNER JOIN TBL_PLAYLIST_SONG ps ON ps.ID_SONG=s.ID_SONG
WHERE ps.ID_PLAYLIST=1 ORDER BY s.SONG_NAME;

PRINT '--- 6. Artist songs (id=1) ---';
SELECT COUNT(*) AS N, ISNULL(SUM(s.PLAYS),0) AS P FROM TBL_PLAYER p
INNER JOIN TBL_SONG s ON s.ID_SONG=p.ID_SONG WHERE p.ID_ARTIST=1;

PRINT '--- 7. Users list ---';
SELECT u.ID_USER, u.USERNAME, u.EMAIL, u.USER_TYPE,
 (SELECT COUNT(*) FROM TBL_PLAYLIST p WHERE p.ID_USER=u.ID_USER) AS PLAYLISTS
FROM TBL_USER u ORDER BY u.USER_TYPE DESC, u.USERNAME;

PRINT '--- 8. Artist albums ---';
SELECT a.ID_ALBUM, a.TITLE_ALBUM FROM TBL_ALBUM a
WHERE a.ID_ALBUM IN (SELECT t.ID_ALBUM FROM TBL_TRACKLIST t
 INNER JOIN TBL_PLAYER p ON p.ID_SONG=t.ID_SONG WHERE p.ID_ARTIST=1)
ORDER BY a.RELEASE_YEAR DESC, a.TITLE_ALBUM;

PRINT '--- 9. Public playlists ---';
SELECT TOP 8 p.ID_PLAYLIST, p.TITLE, u.USERNAME,
 (SELECT COUNT(*) FROM TBL_PLAYLIST_SONG ps WHERE ps.ID_PLAYLIST=p.ID_PLAYLIST) AS TRACKS
FROM TBL_PLAYLIST p INNER JOIN TBL_USER u ON u.ID_USER=p.ID_USER
WHERE p.TYPE=0 ORDER BY p.CREATION_DATE DESC;

PRINT '--- 10. Search pattern ---';
SELECT COUNT(*) AS SONGS FROM TBL_SONG s WHERE s.SONG_NAME LIKE '%dre%';
